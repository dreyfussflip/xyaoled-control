#!/usr/bin/env python3
"""Generate esphome/components/xyao_led/xyao_font.h from a TrueType font.

Default: DejaVu Sans Mono (bundled in custom_components/xyaoled/fonts, free licence).
Glyphs are stored column-major, 16 rows per column (bit n = row n), ASCII 32..126.

    python3 esphome/tools/gen_font.py [--font PATH] [--size 12]
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_FONT = os.path.join(ROOT, "custom_components", "xyaoled", "fonts", "DejaVuSansMono.ttf")
OUT = os.path.join(ROOT, "esphome", "components", "xyao_led", "xyao_font.h")
H = 16


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--size", type=int, default=12)
    ap.add_argument("--preview", default="Hello 32x16!")
    a = ap.parse_args()
    f = ImageFont.truetype(a.font, a.size)
    asc, desc = f.getmetrics()
    top = (H - (asc + desc)) // 2
    widths, cols = [], []
    for code in range(32, 127):
        ch = chr(code)
        adv = max(1, int(round(f.getlength(ch))))
        img = Image.new("1", (adv, H), 0)
        ImageDraw.Draw(img).text((0, top), ch, fill=1, font=f)
        cc = []
        for x in range(adv):
            v = 0
            for y in range(H):
                if img.getpixel((x, y)):
                    v |= 1 << y
            cc.append(v)
        widths.append(adv)
        cols.append(cc)
    offs, o = [], 0
    for c in cols:
        offs.append(o)
        o += len(c)
    name = os.path.splitext(os.path.basename(a.font))[0]
    lines = [
        "#pragma once",
        "#include <cstdint>",
        f"// Generated by esphome/tools/gen_font.py from {name} {a.size}px.",
        "// ASCII 32..126, 16 rows, column-major (bit n = row n).",
        "static const uint8_t XYAO_FONT_W[95] = {" + ",".join(map(str, widths)) + "};",
        "static const uint16_t XYAO_FONT_OFF[95] = {" + ",".join(map(str, offs)) + "};",
        "static const uint16_t XYAO_FONT_COLS[%d] = {" % o + ",".join("0x%04X" % v for c in cols for v in c) + "};",
    ]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    rows = [""] * H
    for ch in a.preview:
        i = ord(ch) - 32
        for v in cols[i]:
            for y in range(H):
                rows[y] += "#" if v >> y & 1 else "."
    print("\n".join(rows))
    print(f"wrote {OUT}: widths {sorted(set(widths))}, {o} columns")


if __name__ == "__main__":
    main()
